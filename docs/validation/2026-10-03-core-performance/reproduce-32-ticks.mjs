import {execFileSync,spawnSync} from 'node:child_process';
import {mkdtempSync,mkdirSync,writeFileSync,readFileSync,cpSync,copyFileSync,symlinkSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join,dirname,resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
import assert from 'node:assert/strict';
const here=dirname(fileURLToPath(import.meta.url)),repo=resolve(here,'../../..'),base='6785ca7dcca09e8e97afd610cfd52176c7a1cfb1';
const work=mkdtempSync(join(tmpdir(),'yunshan-empty-support-'));
const hash=path=>createHash('sha256').update(readFileSync(path)).digest('hex');
mkdirSync(join(work,'before'));mkdirSync(join(work,'after'));mkdirSync(join(work,'scripts'));
const archive=execFileSync('git',['archive',base,'src'],{cwd:repo,maxBuffer:16*1024*1024});
execFileSync('tar',['-x','-C',join(work,'before')],{input:archive});
assert.equal(hash(join(work,'before/src/architecture-floor-plan.ts')),'b4d0c35fb868deedfb10e14128c2f3255a1f3a5f3b54f2f853afb0d2656a4d42');
cpSync(join(work,'before/src'),join(work,'after/src'),{recursive:true});
copyFileSync(join(here,'candidate/architecture-floor-plan.ts'),join(work,'after/src/architecture-floor-plan.ts'));
assert.equal(hash(join(work,'after/src/architecture-floor-plan.ts')),'27431000d8f47ad5c5ece0e8c9319362c0610efda53559854a317995f1fc5f08');
copyFileSync(join(here,'equivalence.mts'),join(work,'scripts/equivalence.mts'));
symlinkSync(join(repo,'node_modules'),join(work,'node_modules'),'dir');
const evidence=join(work,'run01');mkdirSync(evidence);
console.log('Original frozen source and narrow candidate only. Evidence: '+evidence);
const ran=spawnSync(process.execPath,['--import','tsx',join(work,'scripts/equivalence.mts'),evidence],{cwd:repo,stdio:'inherit',timeout:180000});
if(ran.error)throw ran.error;process.exitCode=ran.status??1;
